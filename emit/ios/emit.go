// Emit writes SwiftUI source for every component in mod.
func Emit(mod *nir.Module, w io.Writer) error {
	if err := target.Validate(mod, target.IOS); err != nil {
		return err
	}
	fmt.Fprintln(w, "// Code generated by gsxnative. DO NOT EDIT.")
	fmt.Fprintln(w, "import GSXNativeKit")
	fmt.Fprintln(w, "import SwiftUI")
	fmt.Fprintln(w)
	for i, c := range mod.Components {
		if i > 0 {
			fmt.Fprintln(w)
		}
		if err := emitComponent(w, c); err != nil {
			return err
		}
	}
	return nil
}

func emitComponent(w io.Writer, c *nir.Component) error {
	fmt.Fprintf(w, "public struct %s: GSXComponent {\n", c.Name)
	if c.Props != nil {
		fmt.Fprintln(w, "    public struct Props {")
		for _, f := range c.Props.Fields {
			fmt.Fprintf(w, "        public var %s: %s\n", f.Name, f.Type)
		}
		fmt.Fprintln(w, "    }")
		fmt.Fprintln(w, "    public let props: Props")
	}
	for _, sig := range c.Signals {
		fmt.Fprintf(w, "    @GSXSignal private var %s: %s\n", sig.Name, sig.Type)
	}
	for _, computed := range c.Computeds {
		fmt.Fprintf(w, "    private var %s: %s { %s }\n", computed.Name, computed.Type, emitRxExpr(computed.Body))
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "    public init(props: Props) {")
	fmt.Fprintln(w, "        self.props = props")
	for _, sig := range c.Signals {
		fmt.Fprintf(w, "        self._%s = GSXSignal(wrappedValue: %s)\n", sig.Name, emitRxExpr(sig.Init))
	}
	fmt.Fprintln(w, "    }")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "    public var body: some View {")
	fmt.Fprintf(w, "%s\n", emitView(c.Body, 2))
	fmt.Fprintln(w, "    }")
	fmt.Fprintln(w, "}")
	return nil
}

func emitView(v nir.View, indent int) string {
	pad := strings.Repeat("    ", indent)
	switch n := v.(type) {
	case *nir.Element:
		if n.Tag == "scene3d" {
			return emitScene3D(n, indent)
		}
		if n.Tag == "text" {
			return pad + emitTextElement(n)
		}
		if n.Tag == "textinput" {
			return pad + emitTextInput(n)
		}
		if n.Tag == "textarea" {
			return pad + emitTextArea(n)
		}
		if n.Tag == "checkbox" {
			return pad + emitCheckbox(n)
		}
		if n.Tag == "select" {
			return emitSelect(n, indent)
		}
		for _, h := range n.Handlers {
			if h.Event == "tap" {
				return pad + fmt.Sprintf("Button(%s) { %s }", strconv.Quote(emitChildrenInline(n.Children)), emitRxBlock(h.Body))
			}
		}
		tag := shared.SwiftUITag(n.Tag)
		if tag == "" {
			return pad + "/* unsupported tag: " + n.Tag + " */"
		}
		var sb strings.Builder
		sb.WriteString(pad)
		sb.WriteString(tag)
		sb.WriteString(" {\n")
		for _, child := range n.Children {
			sb.WriteString(emitView(child, indent+1))
			sb.WriteByte('\n')
		}
		sb.WriteString(pad)
		sb.WriteString("}")
		return sb.String()
	case *nir.Text:
		return pad + fmt.Sprintf("Text(%s)", strconv.Quote(n.Value))
	case *nir.ExprHole:
		return pad + fmt.Sprintf(`Text("\(%s)")`, emitRxExpr(&n.Expr))
	case *nir.Conditional:
		return emitConditional(n, indent)
	case *nir.ComponentRef:
		return pad + emitComponentRef(n)
	case *nir.Loop:
		return emitLoop(n, indent)
	default:
		return pad + "/* unsupported view */"
	}
}

func emitScene3D(n *nir.Element, indent int) string {
	pad := strings.Repeat("    ", indent)
	childPad := strings.Repeat("    ", indent+1)
	grandchildPad := strings.Repeat("    ", indent+2)
	nodes := scene3DNodes(n)
	postEffects := scene3DPostEffects(n)
	htmlOverlays := scene3DHTMLOverlays(n)

	var sb strings.Builder
	sb.WriteString(pad)
	sb.WriteString("GSXScene3DView(scene: GSXScene3DScene(\n")
	sb.WriteString(childPad)
	sb.WriteString("width: ")
	sb.WriteString(scene3DDoubleAttr(n, "width", "640"))
	sb.WriteString(",\n")
	sb.WriteString(childPad)
	sb.WriteString("height: ")
	sb.WriteString(scene3DDoubleAttr(n, "height", "360"))
	sb.WriteString(",\n")
	sb.WriteString(childPad)
	sb.WriteString("background: ")
	sb.WriteString(scene3DStringAttr(n, "background", "#101820"))
	if len(postEffects) > 0 {
		sb.WriteString(",\n")
		sb.WriteString(childPad)
		sb.WriteString("postEffects: [\n")
		for i, effect := range postEffects {
			if i > 0 {
				sb.WriteString(",\n")
			}
			sb.WriteString(grandchildPad)
			sb.WriteString(emitScene3DPostEffect(effect))
		}
		sb.WriteByte('\n')
		sb.WriteString(childPad)
		sb.WriteString("]")
	}
	if len(htmlOverlays) > 0 {
		sb.WriteString(",\n")
		sb.WriteString(childPad)
		sb.WriteString("htmlOverlays: [\n")
		for i, overlay := range htmlOverlays {
			if i > 0 {
				sb.WriteString(",\n")
			}
			sb.WriteString(grandchildPad)
			sb.WriteString(emitScene3DHTMLOverlay(overlay, i))
		}
		sb.WriteByte('\n')
		sb.WriteString(childPad)
		sb.WriteString("]")
	}
	sb.WriteString(",\n")
	sb.WriteString(childPad)
	sb.WriteString("nodes: [\n")
	for i, node := range nodes {
		if i > 0 {
			sb.WriteString(",\n")
		}
		sb.WriteString(grandchildPad)
		sb.WriteString(emitScene3DNode(node, i))
	}
	if len(nodes) > 0 {
		sb.WriteByte('\n')
	}
	sb.WriteString(childPad)
	sb.WriteString("]\n")
	sb.WriteString(pad)
	sb.WriteString("))")
	return sb.String()
}

type scene3DNode struct {
	Tag   string
	Attrs []nir.Attr
}

